/**
 * SHA-256 of the certificate under [alias] in [keystore], lowercase hex, or null
 * if the keystore cannot be read. JKS and PKCS12 both load through the JDK's
 * compatible keystore type.
 */
fun signingCertSha256(keystore: File, password: String, alias: String): String? = runCatching {
    val ks = KeyStore.getInstance("PKCS12")
    keystore.inputStream().use { ks.load(it, password.toCharArray()) }
    val cert = ks.getCertificate(alias) ?: return@runCatching null
    MessageDigest.getInstance("SHA-256").digest(cert.encoded).joinToString("") { "%02x".format(it) }
}.getOrNull()

// The certificate phone releases are signed with: the phoneKeyAlias entry in
// the keystore named by keystore.properties (CN=PureTV for Twitch). Android
// installs an update over an existing copy only when the certificates match, so
// the release build checks the key before packaging.
//
// This value changed once, for 1.5.0. Releases up to 1.4.0 used a debug
// keystore (e4ae429a...) that was destroyed with the PC it lived on, and no
// backup existed. Signing-key rotation needs the old private key, so there was
// no way to keep continuity; 1.5.0 therefore requires a reinstall. If this
// check fails, restore the backed-up keystore; never edit the value to pass.
val publishedPhoneSigningSha256 = "0da9841a510f6abce33fd9923859177cb53b068a030fd3f0cf4835d28e2da817"

val verifyReleaseSigningKey by tasks.registering {
    description = "Fails the release build if it would be signed with a different key than published releases."
    doLast {
        if (!hasReleaseSigning) {
            throw GradleException(
                "Refusing to build an unsigned phone release: keystore.properties (storeFile, storePassword, " +
                    "phoneKeyAlias, phoneKeyPassword) is missing. See docs/DEVELOPING.md.",
            )
        }
        val actual = signingCertSha256(
            rootProject.file(keystoreProps.getProperty("storeFile")),
            keystoreProps.getProperty("storePassword"),
            keystoreProps.getProperty("phoneKeyAlias"),
        )
        if (actual != publishedPhoneSigningSha256) {
            throw GradleException(
                "Refusing to build a phone release with " +
                    (if (actual == null) "an unreadable keystore" else "a different key ($actual)") +
                    ". Phone releases are signed with SHA-256 $publishedPhoneSigningSha256.",
            )
        }
    }
}
tasks.matching { it.name == "packageRelease" }.configureEach { dependsOn(verifyReleaseSigningKey) }
