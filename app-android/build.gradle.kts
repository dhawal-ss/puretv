// Release signing credentials live in a gitignored keystore.properties at the
// repo root (see .gitignore), shared with app-tv. The phone key is the entry
// under phoneKeyAlias. When the file is absent (a contributor checkout, or CI
// without the key) the release build stays UNSIGNED rather than failing, and
// verifyReleaseSigningKey refuses to package it.
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) FileInputStream(keystorePropsFile).use { load(it) }
}
val hasReleaseSigning = keystorePropsFile.exists()

